import { mkdir, writeFile } from 'node:fs/promises'

const SNAPSHOT_ID = 'CONMEBOL-2026-09-01'
const FETCHED_AT = '2026-09-01'
const ESPN_ROOT = 'https://site.api.espn.com/apis/site/v2/sports/soccer'

const clubs = [
  ['conmebol-river-plate', 'River Plate', 'arg.1', '16'],
  ['conmebol-boca-juniors', 'Boca Juniors', 'arg.1', '5'],
  ['conmebol-racing', 'Racing Club', 'arg.1', '15'],
  ['conmebol-independiente', 'Independiente', 'arg.1', '11'],
  ['conmebol-nacional', 'Nacional', 'uru.1', '2684'],
  ['conmebol-penarol', 'Peñarol', 'uru.1', '2683'],
  ['conmebol-olimpia', 'Olimpia', 'par.1', '2675'],
  ['conmebol-cerro-porteno', 'Cerro Porteño', 'par.1', '2671'],
  ['conmebol-ldu-quito', 'LDU Quito', 'ecu.1', '4816'],
  ['conmebol-barcelona-sc', 'Barcelona SC', 'ecu.1', '2686'],
  ['conmebol-atletico-nacional', 'Atlético Nacional', 'col.1', '5264'],
  ['conmebol-colo-colo', 'Colo-Colo', 'chi.1', '2688'],
]

function appearances(athlete) {
  const categories = athlete.statistics?.splits?.categories ?? []
  const general = categories.find((category) => category.name === 'general')
  return general?.stats?.find((stat) => stat.name === 'appearances')?.value ?? 0
}

function normalize(athlete) {
  const position = athlete.position?.abbreviation === 'F' ? 'A' : athlete.position?.abbreviation
  return {
    sourceId: `espn-${athlete.id}`,
    name: athlete.displayName,
    position: ['G', 'D', 'M', 'A'].includes(position) ? position : 'M',
    age: athlete.age ?? 23,
    nationality: athlete.citizenshipCountry?.abbreviation ?? 'ARG',
    appearances: appearances(athlete),
  }
}

function selectBalanced(players) {
  const quotas = { G: 2, D: 6, M: 6, A: 4 }
  const sorted = [...players].sort((a, b) => b.appearances - a.appearances || a.name.localeCompare(b.name, 'pt-BR'))
  const selected = []
  for (const position of ['G', 'D', 'M', 'A']) selected.push(...sorted.filter((player) => player.position === position).slice(0, quotas[position]))
  const ids = new Set(selected.map((player) => player.sourceId))
  for (const player of sorted) {
    if (selected.length >= 18) break
    if (!ids.has(player.sourceId)) { selected.push(player); ids.add(player.sourceId) }
  }
  if (selected.length < 18 || !selected.some((player) => player.position === 'G')) throw new Error(`Roster has insufficient positional coverage (${selected.length})`)
  return selected.slice(0, 18).map(({ appearances: _appearances, ...player }) => player)
}

const rosters = []
for (const [id, name, league, espnId] of clubs) {
  const response = await fetch(`${ESPN_ROOT}/${league}/teams/${espnId}/roster`)
  if (!response.ok) throw new Error(`${name}: ESPN ${response.status}`)
  const payload = await response.json()
  const players = selectBalanced((payload.athletes ?? []).map(normalize))
  rosters.push({ id, source: `ESPN ${league} roster, ${FETCHED_AT}`, players })
  process.stdout.write(`${name}: ${players.length} players\n`)
}

const output = `// Generated by scripts/fetch-libertadores-rosters.mjs. Do not edit by hand.\n` +
  `// Player identity snapshot: ${SNAPSHOT_ID}. Emifoot ratings are derived at game creation.\n` +
  `export const LIBERTADORES_ROSTER_SNAPSHOT_ID = ${JSON.stringify(SNAPSHOT_ID)} as const\n` +
  `export const RAW_LIBERTADORES_ROSTERS = ${JSON.stringify(rosters, null, 2)} as const\n`

await mkdir(new URL('../src/data/', import.meta.url), { recursive: true })
await writeFile(new URL('../src/data/libertadores-rosters.generated.ts', import.meta.url), output)
process.stdout.write(`Wrote ${rosters.length} Libertadores rosters to src/data/libertadores-rosters.generated.ts\n`)
